// Generates the files the Flutter app needs from the compiled contract and the deployment, so the app can
// never drift from the contract:
//   lib/blockchain/v2/escrow_v2_abi.g.dart         contract ABI (functions and events), error names, token ABI
//   lib/blockchain/v2/escrow_v2_deployment.g.dart  chain id, contract and token addresses (testnet defaults)
//   test/fixtures/escrow_v2_calldata.json          "golden" call data from ethers, which the Dart tests must match
//
//   npx hardhat compile && node scripts/exportAppArtifacts.js [network]     (default network: bscTestnet)
const fs = require("fs");
const path = require("path");
const { Interface, id, ZeroAddress, MaxUint256, parseEther, getAddress } = require("ethers");

const network = process.argv[2] || "bscTestnet";
const root = path.join(__dirname, "..");
const app = path.join(root, ".."); // plexus-frontend
const dep = JSON.parse(fs.readFileSync(path.join(root, "deployments", `${network}.json`), "utf8"));
const escrowAbi = require(path.join(root, "artifacts/contracts/PlexusEscrowV2.sol/PlexusEscrowV2.json")).abi;
const iface = new Interface(escrowAbi);

// functions and events only (the app does not need the error entries, they are exported as a name table)
const appAbi = escrowAbi.filter((e) => e.type === "function" || e.type === "event");
const errors = {};
iface.forEachError((e) => { errors[e.selector] = e.name; });

const erc20Abi = [
  { type: "function", name: "approve", stateMutability: "nonpayable", inputs: [{ name: "spender", type: "address" }, { name: "value", type: "uint256" }], outputs: [{ name: "", type: "bool" }] },
  { type: "function", name: "allowance", stateMutability: "view", inputs: [{ name: "owner", type: "address" }, { name: "spender", type: "address" }], outputs: [{ name: "", type: "uint256" }] },
  { type: "function", name: "balanceOf", stateMutability: "view", inputs: [{ name: "account", type: "address" }], outputs: [{ name: "", type: "uint256" }] },
  { type: "function", name: "decimals", stateMutability: "view", inputs: [], outputs: [{ name: "", type: "uint8" }] },
  { type: "function", name: "symbol", stateMutability: "view", inputs: [], outputs: [{ name: "", type: "string" }] },
];

const header = "// GENERATED by plexus-escrow/scripts/exportAppArtifacts.js. Do not edit by hand.\n";
const q = (s) => "r'''" + s + "'''";

const abiDart = `${header}// Contract: PlexusEscrowV2. Regenerate after every contract change.

const String escrowV2Abi = ${q(JSON.stringify(appAbi))};

const String erc20Abi = ${q(JSON.stringify(erc20Abi))};

/// 4-byte custom error selector -> error name, to turn a revert into a readable message.
const Map<String, String> escrowV2ErrorNames = ${JSON.stringify(errors, null, 2).replace(/"/g, "'")};
`;

const depDart = `${header}// Deployment: ${network}, deployed ${dep.deployedAt}

const int deployedChainId = ${dep.chainId};
const String deployedEscrowAddress = '${getAddress(dep.escrow)}';
const String deployedTokenAddress = '${getAddress(dep.token)}';
const int deployedFeeBps = ${dep.feeBps};
`;

fs.mkdirSync(path.join(app, "lib/blockchain/v2"), { recursive: true });
fs.writeFileSync(path.join(app, "lib/blockchain/v2/escrow_v2_abi.g.dart"), abiDart);
fs.writeFileSync(path.join(app, "lib/blockchain/v2/escrow_v2_deployment.g.dart"), depDart);

// ---- golden call data -----------------------------------------------------------------------
const A = (n) => getAddress("0x" + n.toString(16).padStart(40, "0"));
const quote = {
  orderRef: id("order-123"), buyer: A(0xb1), seller: A(0x5e), referrer: ZeroAddress,
  productAmount: parseEther("100"), deliveryAmount: parseEther("10"), feeBps: 200, international: false, validUntil: 1893456000,
};
const quoteReferred = { ...quote, orderRef: id("order-456"), referrer: A(0xaa), international: true, productAmount: 1000000000000000007n, deliveryAmount: 0n };
const signature = "0x" + "ab".repeat(32) + "cd".repeat(32) + "1b";
const ref = id("order-123"), hash = id("reason");
const escrowAddr = getAddress(dep.escrow);
const enc = (fn, args) => iface.encodeFunctionData(fn, args);
const tokenIface = new Interface(erc20Abi);
const vectors = {
  note: "Produced by ethers. The Dart tests must produce exactly the same bytes.",
  escrow: escrowAddr,
  quote: Object.fromEntries(Object.entries(quote).map(([k, v]) => [k, typeof v === "bigint" ? v.toString() : v])),
  quoteReferred: Object.fromEntries(Object.entries(quoteReferred).map(([k, v]) => [k, typeof v === "bigint" ? v.toString() : v])),
  signature,
  calls: {
    approve: tokenIface.encodeFunctionData("approve", [escrowAddr, parseEther("110")]),
    approveMax: tokenIface.encodeFunctionData("approve", [escrowAddr, MaxUint256]),
    createOrder: enc("createOrder", [quote, signature]),
    createOrderReferred: enc("createOrder", [quoteReferred, signature]),
    confirmReceipt: enc("confirmReceipt", [ref]),
    openDispute: enc("openDispute", [ref, hash]),
    withdrawDispute: enc("withdrawDispute", [ref]),
    cancelBySeller: enc("cancelBySeller", [ref]),
    markShipped: enc("markShipped", [ref, id("DHL"), id("TRACK"), id("proof"), 1893400000]),
    proposeDeliveryAdjustment: enc("proposeDeliveryAdjustment", [ref, parseEther("25"), hash]),
    acceptDeliveryAdjustment: enc("acceptDeliveryAdjustment", [ref]),
    declineDeliveryAdjustment: enc("declineDeliveryAdjustment", [ref]),
    fundReturnPostage: enc("fundReturnPostage", [ref]),
    markReturnShipped: enc("markReturnShipped", [ref, id("DHL"), id("RET"), id("proof"), 1893400000]),
    confirmReturnReceived: enc("confirmReturnReceived", [ref]),
    contestReturn: enc("contestReturn", [ref, hash]),
    concedeDispute: enc("concedeDispute", [ref]),
    withdraw: enc("withdraw", []),
    withdrawRefund: enc("withdrawRefund", []),
    withdrawRewards: enc("withdrawRewards", []),
  },
  errors,
};

// A getOrder() answer with distinctive values in every field, encoded by ethers. The Dart tests decode it and must
// read the right field from every position (the app reads the Order struct by position).
const orderValues = [
  A(0xb1), A(0x5e), ZeroAddress, parseEther("100"), parseEther("10"), parseEther("25"), 0n, 200, 3000, 2000,
  2 /* status: AdjustmentProposed */, 0, false, true, false, false,
  1700000001, 1700000002, 0, 0, 1700000099 /* adjustmentDeadline */, 0, 0,
];
vectors.getOrderResult = {
  hex: iface.encodeFunctionResult("getOrder", [orderValues]),
  expected: {
    buyer: A(0xb1), seller: A(0x5e), productAmount: parseEther("100").toString(), deliveryAmount: parseEther("10").toString(),
    proposedDelivery: parseEther("25").toString(), status: 2, adjustmentDeadline: 1700000099, extraToPay: parseEther("15").toString(),
  },
};
fs.mkdirSync(path.join(app, "test/fixtures"), { recursive: true });
fs.writeFileSync(path.join(app, "test/fixtures/escrow_v2_calldata.json"), JSON.stringify(vectors, null, 2));
console.log(`Wrote the ABI (${appAbi.length} entries, ${Object.keys(errors).length} errors), the ${network} deployment constants and ${Object.keys(vectors.calls).length} golden call-data vectors.`);
